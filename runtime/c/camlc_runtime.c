/* Strings */

value camlc_string_concat(value a, value b)
{
  CAMLparam2(a, b);
  mlsize_t la = caml_string_length(a), lb = caml_string_length(b);
  value r = caml_alloc_string(la + lb);
  memcpy(Bytes_val(r), String_val(a), la);
  memcpy(Bytes_val(r) + la, String_val(b), lb);
  CAMLreturn(r);
}

