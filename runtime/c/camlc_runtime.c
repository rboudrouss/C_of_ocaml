/* Compilation units and plugins (see camlc.h) */

struct camlc_unit {
  char *name;
  value block;
  struct camlc_unit *next;
};

#define CAMLC_UNIT_BUCKETS 256
static struct camlc_unit *camlc_units[CAMLC_UNIT_BUCKETS];
/* The units and the interfaces, which the domains may load */
static pthread_mutex_t camlc_units_lock = PTHREAD_MUTEX_INITIALIZER;

static unsigned int camlc_unit_hash(const char *name)
{
  unsigned int h = 0;
  for (; *name != 0; name++) h = h * 31 + (unsigned char)*name;
  return h % CAMLC_UNIT_BUCKETS;
}

static struct camlc_unit *camlc_lookup_unit(const char *name)
{
  for (struct camlc_unit *u = camlc_units[camlc_unit_hash(name)]; u != NULL;
       u = u->next)
    if (strcmp(u->name, name) == 0) return u;
  return NULL;
}

value camlc_register_unit(const char *name, value v)
{
  struct camlc_unit *u;
  pthread_mutex_lock(&camlc_units_lock);
  u = camlc_lookup_unit(name);
  if (u == NULL) {
    unsigned int h = camlc_unit_hash(name);
    u = malloc(sizeof(struct camlc_unit));
    if (u == NULL) caml_fatal_error("c_of_ocaml: out of memory");
    u->name = caml_stat_strdup(name);
    u->block = Val_unit;
    caml_register_generational_global_root(&u->block);
    u->next = camlc_units[h];
    camlc_units[h] = u;
  }
  caml_modify_generational_global_root(&u->block, v);
  pthread_mutex_unlock(&camlc_units_lock);
  return Val_unit;
}

/* The interfaces of the program and of the plugins, with their CRCs */
struct camlc_interface {
  char *name;
  char *crc;
  struct camlc_interface *next;
};

static struct camlc_interface *camlc_interfaces[CAMLC_UNIT_BUCKETS];

static struct camlc_interface *camlc_lookup_interface(const char *name)
{
  for (struct camlc_interface *i = camlc_interfaces[camlc_unit_hash(name)];
       i != NULL; i = i->next)
    if (strcmp(i->name, name) == 0) return i;
  return NULL;
}

static void camlc_register_interfaces(const char *const *l)
{
  for (; *l != 0; l += 2)
    if (camlc_lookup_interface(l[0]) == NULL) {
      unsigned int h = camlc_unit_hash(l[0]);
      struct camlc_interface *i = malloc(sizeof(struct camlc_interface));
      if (i == NULL) caml_fatal_error("c_of_ocaml: out of memory");
      i->name = caml_stat_strdup(l[0]);
      i->crc = caml_stat_strdup(l[1]);
      i->next = camlc_interfaces[h];
      camlc_interfaces[h] = i;
    }
}

value camlc_find_unit(const char *name)
{
  struct camlc_unit *u;
  pthread_mutex_lock(&camlc_units_lock);
  u = camlc_lookup_unit(name);
  pthread_mutex_unlock(&camlc_units_lock);
  return u == NULL ? 0 : u->block;
}

/* The message of the error [msg] about the unit [name] */
static const char *camlc_unit_error(char *buf, size_t len, const char *msg,
                                    const char *name)
{
  snprintf(buf, len, "c_of_ocaml: %s %s", msg, name);
  return buf;
}

value camlc_get_unit(const char *name)
{
  struct camlc_unit *u;
  char buf[512];
  pthread_mutex_lock(&camlc_units_lock);
  u = camlc_lookup_unit(name);
  pthread_mutex_unlock(&camlc_units_lock);
  if (u != NULL) return u->block;
  snprintf(buf, sizeof(buf),
           "c_of_ocaml: no implementation available for %s", name);
  return camlc_exception_with_string(FAILURE_EXN, buf);
}

value camlc_load_plugin(const struct camlc_plugin *p)
{
  value res;
  if (p->double_translation != camlc_double_translation)
    caml_failwith(p->double_translation
                      ? "c_of_ocaml: the plugin is compiled with double "
                        "translation, not the program"
                      : "c_of_ocaml: the program is compiled with double "
                        "translation, not the plugin");
  if (p->max_arity > camlc_max_arity) {
    char buf[128];
    snprintf(buf, sizeof(buf),
             "c_of_ocaml: the plugin has functions of arity %d, the program "
             "supports %d",
             p->max_arity, camlc_max_arity);
    caml_failwith(buf);
  }
  {
    char buf[512];
    const char *error = NULL;
    pthread_mutex_lock(&camlc_units_lock);
    for (const char *const *n = p->imports; *n != 0 && error == NULL; n++)
      if (camlc_lookup_unit(*n) == NULL)
        error = camlc_unit_error(buf, sizeof(buf),
                                 "no implementation available for", *n);
    for (const char *const *n = p->units; *n != 0 && error == NULL; n++)
      if (camlc_lookup_unit(*n) != NULL)
        error = camlc_unit_error(
            buf, sizeof(buf), "the plugin defines the unit already loaded", *n);
    for (const char *const *n = p->interfaces; *n != 0 && error == NULL;
         n += 2) {
      struct camlc_interface *i = camlc_lookup_interface(n[0]);
      if (i != NULL && strcmp(i->crc, n[1]) != 0)
        error = camlc_unit_error(buf, sizeof(buf),
                                 "the plugin was compiled against another "
                                 "version of the interface",
                                 n[0]);
    }
    if (error == NULL) {
      camlc_register_interfaces(p->interfaces);
      camlc_register_data(&p->data);
    }
    pthread_mutex_unlock(&camlc_units_lock);
    if (error != NULL) caml_failwith(error);
  }
  res = camlc_ccall0(p->program);
  if (Is_exception_result(res)) caml_raise(Extract_exception(res));
  return Val_unit;
}

