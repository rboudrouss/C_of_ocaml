/* Startup (follows caml_startup_code_exn, without the bytecode) */

static value camlc_run_program(void) { return camlc_program(); }

int main(int argc, char **argv)
{
  char_os *exe_name;
  value res;
  (void)argc;

#if OCAML_VERSION_MAJOR >= 5
  caml_parse_ocamlrunparam();
  if (!caml_startup_aux(0)) return 0;
  caml_init_codefrag();
  caml_init_locale();
  caml_init_custom_operations();
  caml_init_os_params();
  caml_init_gc();
  CAML_RUNTIME_EVENTS_INIT();
  exe_name = caml_executable_name();
  if (exe_name == NULL) exe_name = caml_search_exe_in_path(argv[0]);
  Caml_state->external_raise = NULL;
  caml_init_signals();
#else
  caml_init_domain();
  caml_parse_ocamlrunparam();
  CAML_EVENTLOG_INIT();
  if (!caml_startup_aux(0)) return 0;
  caml_init_locale();
  caml_init_custom_operations();
  exe_name = caml_executable_name();
  if (exe_name == NULL) exe_name = caml_search_exe_in_path(argv[0]);
  caml_init_gc(caml_init_minor_heap_wsz, caml_init_heap_wsz,
               caml_init_heap_chunk_sz, caml_init_percent_free,
               caml_init_max_percent_free, caml_init_major_window,
               caml_init_custom_major_ratio, caml_init_custom_minor_ratio,
               caml_init_custom_minor_max_bsz, caml_init_policy);
  /* The bytecode stack is scanned by the GC, it must exist */
  caml_init_stack(caml_init_max_stack_wsz);
  caml_init_atom_table();
  caml_init_backtrace();
  Caml_state->external_raise = NULL;
  /* Static data are values outside the heap */
  caml_page_table_add(In_static_data, camlc_static_data_begin,
                      camlc_static_data_end);
#endif
  camlc_init_stack();
#if OCAML_VERSION_MAJOR >= 5
  caml_register_generational_global_root(&caml_global_data);
  caml_modify_generational_global_root(
      &caml_global_data, caml_alloc(camlc_global_data_size, 0));
#else
  /* A root of the major GC only (roots_byt.c): it must be in the major
     heap, as the interpreter makes sure */
  caml_global_data = caml_alloc_shr(camlc_global_data_size, 0);
  for (int i = 0; i < camlc_global_data_size; i++)
    Field(caml_global_data, i) = Val_unit;
#endif
  caml_sys_init(exe_name, argv);
  res = camlc_ccall0(camlc_run_program);
  if (Is_exception_result(res))
    caml_fatal_uncaught_exception(Extract_exception(res));
  caml_do_exit(0);
  return 0;
}
