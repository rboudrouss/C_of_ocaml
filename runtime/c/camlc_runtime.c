/* Call [f], turning an exception it raises with longjmp into an
   exception result */
#if OCAML_VERSION_MAJOR >= 5
#define CAMLC_CCALL(call)                                               \
  struct longjmp_buffer buf;                                            \
  volatile value exn = Val_unit;                                        \
  struct caml_exception_context ctx;                                    \
  struct caml_exception_context *saved = Caml_state->external_raise;    \
  value *volatile sp = camlc_sp;                                        \
  value res;                                                            \
  ctx.jmp = &buf;                                                       \
  ctx.local_roots = Caml_state->local_roots;                            \
  ctx.exn_bucket = &exn;                                                \
  if (sigsetjmp(buf.buf, 0)) {                                          \
    Caml_state->external_raise = saved;                                 \
    camlc_sp = sp;                                                      \
    return Make_exception_result(exn);                                  \
  }                                                                     \
  Caml_state->external_raise = &ctx;                                    \
  res = call;                                                           \
  Caml_state->external_raise = saved;                                   \
  return res
#else
/* The handler restores the local roots, and finds the exception in
   [Caml_state->exn_bucket] */
#define CAMLC_CCALL(call)                                               \
  struct longjmp_buffer buf;                                            \
  struct longjmp_buffer *saved = Caml_state->external_raise;            \
  struct caml__roots_block *volatile roots = Caml_state->local_roots;   \
  value *volatile sp = camlc_sp;                                        \
  value res;                                                            \
  if (sigsetjmp(buf.buf, 0)) {                                          \
    Caml_state->external_raise = saved;                                 \
    Caml_state->local_roots = roots;                                    \
    camlc_sp = sp;                                                      \
    return Make_exception_result(Caml_state->exn_bucket);               \
  }                                                                     \
  Caml_state->external_raise = &buf;                                    \
  res = call;                                                           \
  Caml_state->external_raise = saved;                                   \
  return res
#endif

value camlc_ccall0(camlc_prim0 f) { CAMLC_CCALL(f()); }

value camlc_ccall1(camlc_prim1 f, value a) { CAMLC_CCALL(f(a)); }

value camlc_ccall2(camlc_prim2 f, value a, value b) { CAMLC_CCALL(f(a, b)); }

