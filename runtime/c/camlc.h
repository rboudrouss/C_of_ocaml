/* Interface between the C code generated by c_of_ocaml and its runtime
   (camlc_runtime.c), on top of the OCaml bytecode runtime (libcamlrun)
   without its interpreter.

   Conventions of the generated code:

   - The values that must survive a garbage collection live in the frame
     of the function on a shadow stack ([camlc_sp], growing downwards),
     scanned by the GC through [caml_scan_roots_hook].

   - A function of arity [n] is a C function taking its [n] arguments
     followed by its closure. Closures have the layout of the bytecode
     runtime (code pointer, closure info, Infix blocks for mutually
     recursive functions, environment), with C function pointers as code
     pointers.

   - Exceptions are returned: a function returns
     [Make_exception_result(exn)] to raise [exn], and each call site
     checks the result. C primitives raise with [longjmp]
     ([caml_raise]); they are called through wrappers which turn the
     [longjmp] into a returned exception, unless they cannot raise or have
     a version below which returns its exceptions. */

