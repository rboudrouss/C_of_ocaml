/* Integers */

#define Camlc_int_add(a, b) ((value)((uintnat)(a) + (uintnat)(b) - 1))
#define Camlc_int_sub(a, b) ((value)((uintnat)(a) - (uintnat)(b) + 1))
#define Camlc_int_mul(a, b) \
  ((value)((uintnat)((a) - 1) * (uintnat)Long_val(b) + 1))
#define Camlc_int_neg(a) ((value)(2 - (uintnat)(a)))
#define Camlc_int_and(a, b) ((value)((a) & (b)))
#define Camlc_int_or(a, b) ((value)((a) | (b)))
#define Camlc_int_xor(a, b) ((value)(((a) ^ (b)) | 1))
/* The shift count is taken modulo the word size, as by the interpreter on
   wasm: a larger count is undefined behavior in C (Base computes [x lsr
   32] on 31-bit integers, for instance) */
#define Camlc_shift(b) (Long_val(b) & (8 * sizeof(value) - 1))
#define Camlc_int_lsl(a, b) \
  ((value)((((uintnat)(a) - 1) << Camlc_shift(b)) + 1))
#define Camlc_int_lsr(a, b) ((value)(((uintnat)(a) >> Camlc_shift(b)) | 1))
#define Camlc_int_asr(a, b) ((value)(((intnat)(a) >> Camlc_shift(b)) | 1))
/* The quotient is representable: the arguments have one bit less than
   [intnat] */
#define Camlc_int_div_unsafe(a, b) \
  ((value)(((uintnat)(Long_val(a) / Long_val(b)) << 1) + 1))
#define Camlc_int_mod_unsafe(a, b) \
  ((value)(((uintnat)(Long_val(a) % Long_val(b)) << 1) + 1))
#define Camlc_int_compare(a, b) \
  Val_int(((intnat)(a) > (intnat)(b)) - ((intnat)(a) < (intnat)(b)))

static inline value camlc_int_div(value a, value b)
{
  if (CAMLC_UNLIKELY(b == Val_long(0))) return camlc_raise_zero_divide();
  return Camlc_int_div_unsafe(a, b);
}

static inline value camlc_int_mod(value a, value b)
{
  if (CAMLC_UNLIKELY(b == Val_long(0))) return camlc_raise_zero_divide();
  return Camlc_int_mod_unsafe(a, b);
}

/* Floats */

static inline value camlc_float_compare_unboxed(double x, double y)
{
  /* As caml_float_compare: nan is equal to itself and less than any
     other float */
  return Val_int((x > y) - (x < y) + (x == x) - (y == y));
}

static inline double camlc_double_of_bits(int64_t i)
{
  union { int64_t i; double d; } u;
  u.i = i;
  return u.d;
}

static inline int64_t camlc_bits_of_double(double d)
{
  union { int64_t i; double d; } u;
  u.d = d;
  return u.i;
}

static inline value camlc_store_double_flat(value a, value i, double d)
{
  Store_double_flat_field(a, Long_val(i), d);
  return Val_unit;
}

/* Write barrier: no work for an integer replacing an integer (the major
   GC only cares about the pointers overwritten or written), nor for a
   block of the minor heap */
static inline void camlc_modify(volatile value *fp, value v)
{
  if ((Is_long(v) && Is_long(*fp)) || Is_young((value)fp)) *fp = v;
  else caml_modify(fp, v);
}

/* Arrays and strings */

static inline value camlc_check_bound(value a, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= Wosize_val(a)))
    return camlc_raise_bound_error();
  return a;
}

static inline value camlc_check_bound_float(value a, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= Wosize_val(a) / Double_wosize))
    return camlc_raise_bound_error();
  return a;
}

static inline mlsize_t camlc_array_length(value a)
{
  if (Tag_val(a) == Double_array_tag) return Wosize_val(a) / Double_wosize;
  return Wosize_val(a);
}

static inline value camlc_check_bound_gen(value a, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= camlc_array_length(a)))
    return camlc_raise_bound_error();
  return a;
}

static inline value camlc_array_unsafe_get(value a, value i)
{
  if (Tag_val(a) == Double_array_tag)
    return caml_copy_double(Double_flat_field(a, Long_val(i)));
  return Field(a, Long_val(i));
}

/* [caml_string_length], inline */
static inline mlsize_t camlc_string_length(value s)
{
  mlsize_t last = Bosize_val(s) - 1;
  return last - Byte(s, last);
}

static inline value camlc_string_get(value s, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= camlc_string_length(s)))
    return camlc_raise_bound_error();
  return Val_int(Byte_u(s, Long_val(i)));
}

static inline value camlc_bytes_set(value s, value i, value c)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= camlc_string_length(s)))
    return camlc_raise_bound_error();
  Byte_u(s, Long_val(i)) = (unsigned char)Long_val(c);
  return Val_unit;
}

/* The 16, 32 and 64-bit accesses to strings and bytes
   ([caml_string_get32], [caml_bytes_set64]...): the bound check returns
   [Val_unit] or the exception, then the access cannot fail, on unboxed
   integers */
static inline value camlc_check_bytes_access(value s, value i, intnat width)
{
  if (CAMLC_UNLIKELY(Long_val(i) < 0
                     || Long_val(i) > (intnat)camlc_string_length(s) - width))
    return camlc_raise_bound_error();
  return Val_unit;
}

