/* Interface between the C code generated by c_of_ocaml and its runtime
   (camlc_runtime.c), on top of the OCaml bytecode runtime (libcamlrun)
   without its interpreter.

   Conventions of the generated code:

   - The values that must survive a garbage collection live in the frame
     of the function on a shadow stack ([camlc_sp], growing downwards),
     scanned by the GC through [caml_scan_roots_hook].

   - A function of arity [n] is a C function taking its [n] arguments
     followed by its closure. Closures have the layout of the bytecode
     runtime (code pointer, closure info, Infix blocks for mutually
     recursive functions, environment), with C function pointers as code
     pointers.

   - Exceptions are returned: a function returns
     [Make_exception_result(exn)] to raise [exn], and each call site
     checks the result. C primitives raise with [longjmp]
     ([caml_raise]); they are called through wrappers which turn the
     [longjmp] into a returned exception. */

#ifndef CAMLC_H
#define CAMLC_H

#define CAML_INTERNALS
#include <stddef.h>
#include <string.h>
#include <math.h>
/* <caml/fail.h> redefines sigsetjmp and siglongjmp as emscripten's
   <setjmp.h> does */
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wmacro-redefined"
#include <caml/mlvalues.h>
#include <caml/alloc.h>
#include <caml/memory.h>
#include <caml/gc.h>
#include <caml/fail.h>
#include <caml/callback.h>
#include <caml/custom.h>
#include <caml/domain_state.h>
#pragma clang diagnostic pop

/* Tail calls, with the tail call extension of WebAssembly (-mtail-call):
   the caller and the callee must have the same signature */
#ifdef __wasm_tail_call__
#define CAMLC_MUSTTAIL __attribute__((musttail))
#else
#define CAMLC_MUSTTAIL
#endif

#define CAMLC_LIKELY(x) __builtin_expect(!!(x), 1)
#define CAMLC_UNLIKELY(x) __builtin_expect(!!(x), 0)

/* Statically allocated blocks are never marked by the GC */
#define CAMLC_STATIC_COLOR (3 << 8)

/* The runtime's table of global data, holding the predefined exceptions */
extern value caml_global_data;

/* Shadow stack */
extern value *camlc_sp;
extern value *camlc_stack_limit;

/* Returns the Stack_overflow exception, as an exception result */
value camlc_stack_overflow(void);

/* Generic application: apply [f] to the [n] arguments [args] */
value camlc_applyv(value f, int n, value *args);

/* Defined by the generated code: call [f] of arity [n] with [args] */
value camlc_call_exact(value f, int n, value *args);
/* Code pointers of the partial applications of each arity */
extern const value camlc_pap_code[];
extern const int camlc_max_arity;
/* Allocate the closure for the partial application of [f] to [n]
   arguments [args] */
value camlc_make_pap(value f, int n, value *args);

/* Wrappers for C primitives, which may raise with longjmp */
typedef value (*camlc_prim0)(void);
typedef value (*camlc_prim1)(value);
typedef value (*camlc_prim2)(value, value);
typedef value (*camlc_prim3)(value, value, value);
typedef value (*camlc_prim4)(value, value, value, value);
typedef value (*camlc_prim5)(value, value, value, value, value);
typedef value (*camlc_primv)(value *, int);

value camlc_ccall0(camlc_prim0 f);
value camlc_ccall1(camlc_prim1 f, value a);
value camlc_ccall2(camlc_prim2 f, value a, value b);
value camlc_ccall3(camlc_prim3 f, value a, value b, value c);
value camlc_ccall4(camlc_prim4 f, value a, value b, value c, value d);
value camlc_ccall5(camlc_prim5 f, value a, value b, value c, value d,
                   value e);
value camlc_ccallv(camlc_primv f, value *argv, int argc);

/* Exceptions, returned as exception results */
value camlc_raise_zero_divide(void);
value camlc_raise_bound_error(void);
value camlc_raise_unhandled_effect(void);

/* Integers */

#define Camlc_int_add(a, b) ((value)((uintnat)(a) + (uintnat)(b) - 1))
#define Camlc_int_sub(a, b) ((value)((uintnat)(a) - (uintnat)(b) + 1))
#define Camlc_int_mul(a, b) \
  ((value)((uintnat)((a) - 1) * (uintnat)Long_val(b) + 1))
#define Camlc_int_neg(a) ((value)(2 - (uintnat)(a)))
#define Camlc_int_and(a, b) ((value)((a) & (b)))
#define Camlc_int_or(a, b) ((value)((a) | (b)))
#define Camlc_int_xor(a, b) ((value)(((a) ^ (b)) | 1))
#define Camlc_int_lsl(a, b) \
  ((value)((((uintnat)(a) - 1) << Long_val(b)) + 1))
#define Camlc_int_lsr(a, b) ((value)(((uintnat)(a) >> Long_val(b)) | 1))
#define Camlc_int_asr(a, b) ((value)(((intnat)(a) >> Long_val(b)) | 1))
/* The quotient is representable: the arguments have one bit less than
   [intnat] */
#define Camlc_int_div_unsafe(a, b) \
  ((value)(((uintnat)(Long_val(a) / Long_val(b)) << 1) + 1))
#define Camlc_int_mod_unsafe(a, b) \
  ((value)(((uintnat)(Long_val(a) % Long_val(b)) << 1) + 1))
#define Camlc_int_compare(a, b) \
  Val_int(((intnat)(a) > (intnat)(b)) - ((intnat)(a) < (intnat)(b)))

static inline value camlc_int_div(value a, value b)
{
  if (CAMLC_UNLIKELY(b == Val_long(0))) return camlc_raise_zero_divide();
  return Camlc_int_div_unsafe(a, b);
}

static inline value camlc_int_mod(value a, value b)
{
  if (CAMLC_UNLIKELY(b == Val_long(0))) return camlc_raise_zero_divide();
  return Camlc_int_mod_unsafe(a, b);
}

/* Floats */

static inline value camlc_float_compare(value a, value b)
{
  double x = Double_val(a), y = Double_val(b);
  /* As caml_float_compare: nan is equal to itself and less than any
     other float */
  return Val_int((x > y) - (x < y) + (x == x) - (y == y));
}

/* Write barrier: no work for a block of the minor heap */
static inline void camlc_modify(volatile value *fp, value v)
{
  if (Is_young((value)fp)) *fp = v;
  else caml_modify(fp, v);
}

/* Arrays and strings */

static inline value camlc_check_bound(value a, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= Wosize_val(a)))
    return camlc_raise_bound_error();
  return a;
}

static inline value camlc_check_bound_float(value a, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= Wosize_val(a) / Double_wosize))
    return camlc_raise_bound_error();
  return a;
}

static inline mlsize_t camlc_array_length(value a)
{
  if (Tag_val(a) == Double_array_tag) return Wosize_val(a) / Double_wosize;
  return Wosize_val(a);
}

static inline value camlc_check_bound_gen(value a, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= camlc_array_length(a)))
    return camlc_raise_bound_error();
  return a;
}

static inline value camlc_array_unsafe_get(value a, value i)
{
  if (Tag_val(a) == Double_array_tag)
    return caml_copy_double(Double_flat_field(a, Long_val(i)));
  return Field(a, Long_val(i));
}

static inline value camlc_string_get(value s, value i)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= caml_string_length(s)))
    return camlc_raise_bound_error();
  return Val_int(Byte_u(s, Long_val(i)));
}

static inline value camlc_bytes_set(value s, value i, value c)
{
  if (CAMLC_UNLIKELY((uintnat)Long_val(i) >= caml_string_length(s)))
    return camlc_raise_bound_error();
  Byte_u(s, Long_val(i)) = (unsigned char)Long_val(c);
  return Val_unit;
}

value camlc_string_concat(value a, value b);

/* Objects */
value camlc_oo_cache_id(void);
value camlc_get_cached_method(value obj, value tag, value cache_id);

/* Allocation of a block of [wosize] fields, which the caller must then
   initialize with plain stores (small blocks) or [caml_initialize]
   (large blocks, [wosize > Max_young_wosize]) before the next
   allocation. */
static inline value camlc_alloc_small(mlsize_t wosize, tag_t tag)
{
  value v;
  Alloc_small(v, wosize, tag, Alloc_small_enter_GC);
  return v;
}

static inline value camlc_box_double(double d)
{
  value v = camlc_alloc_small(Double_wosize, Double_tag);
  Store_double_val(v, d);
  return v;
}

#endif
