(* Embed the files given on the command line as an OCaml list of (base
   name, contents) *)

let read_file f =
  let ic = open_in_bin f in
  let s = really_input_string ic (in_channel_length ic) in
  close_in ic;
  s

let () =
  print_string "let files = [\n";
  for i = 1 to Array.length Sys.argv - 1 do
    let f = Sys.argv.(i) in
    Printf.printf "  %S, %S;\n" (Filename.basename f) (read_file f)
  done;
  print_string "]\n"
